  /* ⚠️ **מודגש בלי HTML גולמי מהתוכן.** הטקסט עובר escape מלא,
     ורק אחר כך מומרות הכוכביות הכפולות ל-<b>. כך אי אפשר להחדיר
     תגיות דרך התוכן, וגם אם מישהו יערוך את המאמרים בעתיד. */
