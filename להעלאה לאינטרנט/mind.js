        'רשות הטבע':   ['רשות הטבע', 'רטג', 'פקח', 'פקחים', 'רשות הטבע והגנים'],
        'מדוזה':       ['מדוזה', 'מדוזות'],
        'עשבי ים':     ['עשבי ים', 'עשב ים', 'אצות', 'מרעה'],
        'נדידה':       ['נדידה', 'נדידות', 'מיגרציה', 'נודדים'],
        'החתמה':       ['החתמה', 'ההחתמה'],
        'סירה':        ['סירה', 'סירות', 'מדחף', 'ספינה'],
        'אקלים':       ['אקלים', 'התחממות', 'שינוי אקלים'],
