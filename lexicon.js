  function expandTokens(tokens) {
    ensure();
    var out = tokens.slice();
    var seen = Object.create(null);
    for (var i = 0; i < tokens.length; i++) seen[tokens[i]] = 1;
    for (var t = 0; t < tokens.length; t++) {
      var word = tokens[t];
      var syns = map[word] || map[stripPrefix(word)];
      if (!syns) continue;
      for (var s = 0; s < syns.length; s++) {
        if (!seen[syns[s]]) {
          seen[syns[s]] = 1;
          out.push(syns[s]);
        }
      }
    }
    return out;
  }
