  /* האם המילה שייכת לעולם צבי הים */
  function isTopicWord(word) {
    ensure();
    var w = normalize(word);
    if (topicSet[w]) return true;
    var s = stripPrefix(w);
    if (topicSet[s]) return true;
    // התאמת תחילית: "צבים", "הצבים", "צביים"
    for (var key in topicSet) {
      if (key.length >= 3 && (w.indexOf(key) === 0 || s.indexOf(key) === 0)) return true;
    }
    return false;
  }
