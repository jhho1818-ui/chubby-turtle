  /* מדד לשאלה שלמה: כמה היא "בתחום" */
  function topicScore(text) {
    ensure();
    var words = normalize(text).split(' ').filter(Boolean);
    var hits = 0, off = 0;
    for (var i = 0; i < words.length; i++) {
      if (isTopicWord(words[i])) hits++;
      if (isOffTopicWord(words[i])) off++;
    }
    return { words: words.length, topic: hits, off: off };
  }
