def build():
    brain = {
        "meta": meta,
        "greetings": greetings,
        "offtopic": offtopic,
        "facts": facts,
        "data": [],
    }

    seen_keys = {}
    for cat, keys, response, follow in DATA:
        for k in keys:
            kk = k.strip().lower()
            if kk in seen_keys:
                raise ValueError('מילת מפתח כפולה: "%s" (כבר ב-"%s")' % (k, seen_keys[kk]))
            seen_keys[kk] = keys[0]
        entry = {"lang": "he", "category": cat, "keys": keys, "response": response}
        if follow:
            entry["follow"] = follow
        brain["data"].append(entry)

    # ——— שכבת התקשורת הבין-אישית ———
    # ⚠️ מגיעה **אחרי** הערכים הידניים ו**לפני** המילון:
    # ערך ידני כתוב בשפה של ילד וגובר; מונח מילוני יבש נכנע
    # לתשובה אנושית. מפתח תפוס — נשמט בשקט ולא מפיל את הבנייה,
    # כי כאן נכתבות מאות וריאציות ואי אפשר לזכור ידנית מה תפוס.
    social_added = 0
    for item in SOCIAL:
        keys, responses = item[0], item[1]
        follow = item[2] if len(item) > 2 else []
        fresh = []
        for k in keys:
            kk = k.strip().lower()
            if kk in seen_keys:
                continue
            seen_keys[kk] = keys[0]
            fresh.append(k)
        if not fresh:
            continue
        entry = {
            "lang": "he",
            "category": "שיחה",
            "keys": fresh,
            "response": responses if len(responses) > 1 else responses[0],
        }
        if follow:
            entry["follow"] = follow
        brain["data"].append(entry)
        social_added += 1

    # ——— המילון ———
    # ⚠️ כאן **לא** זורקים שגיאה על כפילות אלא מדלגים: הערכים
    # הידניים למעלה כתובים בשפה של ילד ותמיד גוברים על ההגדרה
    # המילונית. מונח שכל מילות המפתח שלו כבר תפוסות — נשמט.
    gloss_added = 0
    gloss_skipped = 0
    for term, body in load_glossary():
        fresh = []
        for k in glossary_keys(term):
            kk = k.strip().lower()
            if kk in seen_keys:
                continue
            seen_keys[kk] = term
            fresh.append(k)
        if not fresh:
            gloss_skipped += 1
            continue
        brain["data"].append({
            "lang": "he",
            "category": "מילון",
            "keys": fresh,
            "response": body
        })
        gloss_added += 1

    # ⚠️⚠️ **אוצר המילים של התחום נגזר מהמאגר, לא נכתב ביד.**
    #
    # שומר התחום של צאבי בדק מול רשימת מילים ידנית ב-lexicon.js.
    # ברגע שנוספו מאות מונחי מילון, כל מונח טכני שלא היה ברשימה
    # ההיא נראה לשומר כמו נושא זר — ו"מה זה פיברופפילומה" קיבל
    # את התשובה "אני מדבר רק על צבי ים".
    #
    # הפתרון: כל מילה שמופיעה במילות המפתח של המאגר היא בהגדרה
    # מילה מהתחום. הרשימה נבנית אוטומטית בכל בנייה ולכן לעולם
    # לא מתיישנת.
    topic = set()
    for e in brain["data"]:
        for k in e["keys"]:
            for w in k.replace("-", " ").split():
                w = w.strip("?!.,:;\"'()").lower()
                if len(w) >= 3:
                    topic.add(w)
    brain["topic"] = sorted(topic)

    text = json.dumps(brain, ensure_ascii=False, indent=1)
    OUT.write_text(text, encoding="utf-8")
    OUT_TOOLS.write_text(text, encoding="utf-8")

    # ⚠️ גם כקובץ JS. הסיבה נמדדה אצל המשתמש: fetch("brain.json")
    # נכשל כשפותחים את index.html ישירות מהדיסק (file://) וגם כאשר
    # Service Worker ישן שולט בדף — והילד קיבל "לא הצלחתי לטעון את
    # מאגר הידע". תגית <script> עובדת בכל מצב, בלי רשת ובלי שרת.
    OUT_JS.write_text(
        "/* נוצר אוטומטית על ידי tools/build-brain.py — אין לערוך ידנית.\n"
        "   © דניאל אברהם חדאד | CBY-T7R4L2E9 */\n"
        "window.CBY_BRAIN = " + text + ";\n",
        encoding="utf-8")

    total_keys = sum(len(e["keys"]) for e in brain["data"])
    print("brain.json נבנה בהצלחה:")
    print("  ערכים        :", len(brain["data"]))
    print("  מתוכם שיחה   :", social_added)
    print("  מתוכם מילון  :", gloss_added, "(נשמטו ככפולים: %d)" % gloss_skipped)
    print("  מילות מפתח   :", total_keys)
    print("  עובדות       :", len(brain["facts"]))
    print("  אוצר תחום    :", len(brain["topic"]), "מילים")
    print("  נתיב         :", OUT)
    print("  גם כ-JS      :", OUT_JS)


if __name__ == "__main__":
    build()
