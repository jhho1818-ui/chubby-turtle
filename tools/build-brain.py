def load_glossary():
    """קורא את tools/glossary.txt ומחזיר [(מונח, הסבר)]."""
    if not GLOSSARY.exists():
        return []
    out = []
    for raw in GLOSSARY.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if ": " not in line:
            continue
        term, _, body = line.partition(": ")
        term = term.strip()
        body = body.strip()
        if term and body:
            out.append((term, body))
    return out


def glossary_keys(term):
    """מילות המפתח של מונח אחד — מהצורה המדויקת ועד איך שילד שואל."""
    keys = [term, "מה זה " + term]
    words = term.split()

    # צורה בלי מילת הפתיחה הכללית
    if len(words) > 1 and words[0] in LEAD_WORDS:
        short = " ".join(words[1:])
        if len(short) > 3:
            keys.append(short)
            keys.append("מה זה " + short)

    # מונח דו-מילי מקבל גם "ספר על X" — ניסוח נפוץ אצל ילדים
    if len(words) <= 3:
        keys.append("ספר על " + term)

    # ⚠️ **שתי המילים הראשונות** של מונח ארוך. נמדד: "כלבי גישוש
    # לאיתור קינים" לא נמצא כששאלו "מה זה כלבי גישוש", כי אף
    # מילת מפתח לא התאימה לניסוח הקצר שאדם באמת משתמש בו.
    if len(words) >= 3:
        head = " ".join(words[:2])
        keys.append(head)
        keys.append("מה זה " + head)

    # ⚠️ **מילה טכנית ארוכה עומדת בפני עצמה.** "מחלת הפיברופפילומה"
    # נכשל על "מה זה פיברופפילומה" — הילד זוכר את המילה המיוחדת,
    # לא את הצירוף המלא. מילה באורך 7+ היא נדירה מספיק כדי שלא
    # תיצור התנגשויות.
    for w in words:
        bare = w[1:] if (len(w) > 7 and w[0] in "הוב") else w
        if len(bare) >= 7:
            keys.append(bare)
            keys.append("מה זה " + bare)

    return keys


