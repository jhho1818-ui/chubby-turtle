    function pick(arr, avoid) {
        if (!arr || !arr.length) return '';
        for (var i = 0; i < arr.length; i++) {
            if (arr[i] !== avoid) return arr[i];
        }
        return arr[0];
    }
    function pickRandom(arr) {
        return arr[Math.floor(Math.random() * arr.length)];
    }
/* © דניאל אברהם חדאד · CBY-T7R4L2E9 */

    /* מחזיר תשובת המשך, או null אם אין נושא פתוח / אין חומר.
       ⚠️ null הוא תשובה לגיטימית וחשובה: הוא מחזיר את השליטה
       לזרימה הקיימת במקום להמציא. */
    function continueTopic(text, brain, lang) {
        lang = lang || 'he';
        if (!hasOpenTopic()) return null;
        if (!isFollowUp(text, lang)) return null;
/* © דניאל אברהם חדאד · CBY-T7R4L2E9 */

        // (א) לערך הנוכחי יש עוד נוסח שלא נאמר — הדרך הזולה והטובה
        var cur = state.topicEntry;
        if (cur && Array.isArray(cur.response) && cur.response.length > 1) {
            for (var i = 0; i < cur.response.length; i++) {
                var cand = cur.response[i];
                if (!wasSaid(cand)) {
                    return { text: cand, entry: cur, how: 'variant' };
                }
            }
        }
/* © דניאל אברהם חדאד · CBY-T7R4L2E9 */

        // ⚠️⚠️ **פתרון כינוי גוף — החוליה שהייתה חסרה.**
        //
        // דווח: "שאלתי לגבי המלכה אם היא יכולה למות, והוא דיבר
        // איתי על משקל".
        //
        // במשפט "היא יכולה למות" אין את המילה "מלכה" בכלל. הכינוי
        // "היא" הוא מילת עצירה ונזרק, ונשארו רק "יכולה" ו"למות" —
        // שתי מילים שלא מצביעות על שום נושא. הדירוג חיפש ערך
        // שמתאים להן ומצא משהו אקראי.
        //
        // בן אדם פותר את זה בלי לחשוב: "היא" = מה שדיברנו עליו.
        // בדיוק את זה עושים כאן — מחליפים את הכינוי בשם הנושא
        // הפתוח לפני הדירוג, וכך "היא יכולה למות" נקרא כ"המלכה
        // יכולה למות".
        var askText = text;
        if (state.headWord && /^ו?(היא|הוא|הם|הן|זה|זאת|אותה|אותו)(?![֐-׿])/.test(String(text).trim())) {
            askText = state.headWord + ' ' + String(text).replace(/^ו?(היא|הוא|הם|הן|זה|זאת|אותה|אותו)/, '').trim();
        }
/* © דניאל אברהם חדאד · CBY-T7R4L2E9 */

        // (ב) ערך קרוב באותו נושא — מדורג לפי מה שנשאל עכשיו
        var rel = relatedEntries(brain, lang, 6, askText);
        for (var k = 0; k < rel.length; k++) {
            // ⚠️ ערך שנבחר בזכות מילה מהשאלה עצמה גובר על סף
            // החפיפה עם הנושא: הילד הצביע עליו במפורש.
            if (!rel[k].askHits && rel[k].hits < MIN_HITS) continue;
            var e = rel[k].entry;
            var body = Array.isArray(e.response) ? e.response[0] : e.response;
            if (!body || wasSaid(body)) continue;
            var lead = pickRandom(lang === 'he' ? CONNECT_HE : CONNECT_EN);
            // ⚠️ הגוף נרשם בנפרד מהטקסט המלא. wasSaid משווה 80 תווים
            // ראשונים, ומשפט פתיחה משתנה ("תוספת קטנה: ") היה מזיז
            // את החלון ומסתיר חזרה על אותו תוכן בדיוק.
            state.said.unshift(String(body).slice(0, 80));
            state.said = state.said.slice(0, 6);
            return { text: lead + body, entry: e, how: 'related' };
        }
/* © דניאל אברהם חדאד · CBY-T7R4L2E9 */

        return null;
    }
/* © דניאל אברהם חדאד · CBY-T7R4L2E9 */

    function wasSaid(t) {
        if (!t) return true;
        var head = String(t).slice(0, 80);
        return state.said.indexOf(head) !== -1;
    }
/* © דניאל אברהם חדאד · CBY-T7R4L2E9 */

    // ------------------------------------------------------------------
    // 6. ברירת מחדל שמכבדת את הילד
    // ------------------------------------------------------------------
    // ⚠️ "לא הבנתי" הוא קיר. ילד ששומע אותו פעמיים מפסיק לנסות.
    // במקום זה מציעים את מה שצאבי **כן** יודע ושהכי קרוב למה
    // שנשאל — כך גם אי-הבנה מקדמת את השיחה במקום לעצור אותה.
    //
    // ⚠️ מציעים רק כשיש באמת קרבה. הצעה אקראית ("אולי התכוונת
    // לשעווה?") אחרי שאלה על משהו אחר לגמרי היא בלבול נוסף, לא
    // עזרה.
    function suggestions(text, brain, lang, howMany) {
        lang = lang || 'he';
        var cw = contentWords(text, lang);
        if (!cw.length) return [];
        var m = buildIdf(brain, lang);
        var scored = [];
        for (var i = 0; i < brain.length; i++) {
            var e = brain[i];
            if (!e || !e.keys || e.keys[0] === 'default') continue;
            if ((e.lang || 'he') !== lang) continue;
            var ew = contentWords(e.keys.join(' '), lang);
            var weight = 0, best = 0;
            for (var j = 0; j < ew.length; j++) {
                if (!hasWord(cw, ew[j])) continue;
                var wgt = idf(ew[j], m);
                weight += wgt;
                if (wgt > best) best = wgt;
            }
            // ⚠️ אותו כלל כמו בהמשכי שיחה: חייבת להיות מילה אחת
            // לפחות שבאמת מבחינה. ערך שחולק רק מילים שכיחות אינו
            // הצעה — הוא רעש שנשמע כמו הצעה.
            if (best < 1.8) continue;
            scored.push({ key: e.keys[0], score: weight / Math.sqrt(ew.length || 1) });
        }
        scored.sort(function (a, b) { return b.score - a.score; });
        var out = [], seen = {};
        for (var m = 0; m < scored.length && out.length < (howMany || 2); m++) {
            var k = scored[m].key;
            if (seen[k]) continue;
            seen[k] = 1;
            out.push(k);
        }
        return out;
    }
/* © דניאל אברהם חדאד · CBY-T7R4L2E9 */

    function fallback(text, brain, lang) {
        lang = lang || 'he';
        var s = suggestions(text, brain, lang, 2);
        if (!s.length) return null;                  // אין קרבה — לא ממציאים
        if (lang === 'he') {
            return s.length === 1
                ? 'לא בטוח שהבנתי בדיוק 🐢 אבל אני יודע לספר על "' + s[0] + '" — רוצה?'
                : 'לא בטוח שהבנתי בדיוק 🐢 אני כן יודע על "' + s[0] + '" ועל "' + s[1] + '" — מה מעניין אותך?';
        }
        return s.length === 1
            ? 'Not sure I got that 🐢 but I can tell you about "' + s[0] + '" — want to?'
            : 'Not sure I got that 🐢 I do know about "' + s[0] + '" and "' + s[1] + '" — which one?';
    }
