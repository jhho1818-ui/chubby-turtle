    function contentWords(text, lang) {
        var stop = stopFor(lang);
        var raw = String(text || '')
            .toLowerCase()
            .replace(/["'`״׳()\[\]{}.,!?;:\-–—]/g, ' ')
            .split(/\s+/);
        var out = [], seen = {};
        for (var i = 0; i < raw.length; i++) {
            var w = raw[i];
            if (!w || w.length < 2) continue;
            if (stop[w]) continue;
            // ⚠️ מילת שאלה עם ו' החיבור היא עדיין מילת רקע.
            // "ולמה?" הכיל לפי הספירה מילת תוכן אחת, ולכן לא זוהה
            // כמשפט המשך ריק — והילד קיבל שוב בדיוק את התשובה
            // הקודמת במקום המשך.
            if (w.length > 2 && w.charAt(0) === 'ו' && stop[w.slice(1)]) continue;
            if (seen[w]) continue;
            seen[w] = 1;
            out.push(w);
        }
        return out;
    }
