    var idfMap = null, idfBrain = null;
    function buildIdf(brain, lang) {
        if (idfMap && idfBrain === brain) return idfMap;
        var df = {}, n = 0;
        for (var i = 0; i < brain.length; i++) {
            var e = brain[i];
            if (!e || !e.keys) continue;
            if ((e.lang || 'he') !== lang) continue;
            n++;
            var ew = contentWords(e.keys.join(' '), lang);
            for (var j = 0; j < ew.length; j++) df[ew[j]] = (df[ew[j]] || 0) + 1;
            // מונים גם את הצורה בלי תחילית, כדי ש"בעוקץ" ו"עוקץ"
            // יחלקו את אותה שכיחות ולא ייראו כשתי מילים נדירות.
            for (var q = 0; q < ew.length; q++) {
                var wq = ew[q];
                if (wq.length > 3 && /^[והבלמכש]/.test(wq)) {
                    var bare = wq.slice(1);
                    if (df[bare]) df[wq] = Math.max(df[wq] || 0, df[bare]);
                }
            }
        }
        idfMap = { df: df, n: Math.max(n, 1) };
        idfBrain = brain;
        return idfMap;
    }
    function idf(word, m) {
        var d = m.df[word] || 0;
        if (!d) return 0;
        return Math.log(m.n / d);
    }
